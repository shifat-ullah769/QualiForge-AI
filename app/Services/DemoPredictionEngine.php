<?php

namespace App\Services;

use App\Models\Dataset;
use Illuminate\Validation\ValidationException;

class DemoPredictionEngine
{
    public function run(Dataset $dataset): array
    {
        if ($dataset->validation_status !== 'passed') {
            throw ValidationException::withMessages([
                'dataset' => 'Dataset must pass validation before prediction.',
            ]);
        }

        if (!$dataset->row_count || $dataset->row_count < 1) {
            throw ValidationException::withMessages([
                'dataset' => 'Dataset must contain at least one data row.',
            ]);
        }

        /*
         * DEMO ONLY:
         * These values are illustrative placeholders.
         * They are NOT generated by a trained AI model.
         */

        return [
            'model_version' => 'demo-v1.0',

            'summary' => [
                'prediction_type' => 'manufacturing_quality',
                'total_records' => $dataset->row_count,
                'predicted_defect_rate' => 3.8,
                'quality_score' => 96.2,
                'risk_level' => 'low',
                'predicted_defect_records' => (int) round(
                    $dataset->row_count * 0.038
                ),
            ],

            'result_payload' => [
                'demo_mode' => true,
                'notice' => 'Illustrative demo results. Not actual AI predictions.',

                'quality_assessment' => [
                    'classification' => 'Good',
                    'risk_level' => 'Low',
                    'quality_score' => 96.2,
                ],

                'defect_analysis' => [
                    'predicted_defect_rate' => 3.8,
                    'predicted_defect_records' => (int) round(
                        $dataset->row_count * 0.038
                    ),
                ],

                'recommendations' => [
                    'Continue routine quality inspections.',
                    'Monitor defect trends across production batches.',
                    'Review production parameters regularly.',
                ],
            ],
        ];
    }
}
